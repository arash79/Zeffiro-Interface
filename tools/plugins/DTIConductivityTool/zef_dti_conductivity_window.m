    'Text', 'Apply to compartments:', ...
    'Position', [PANEL_MARGIN+10 COMPART_Y+80 150 30]);

% Build list of compartments with display names
compartment_items = {};
compartment_items_data = {};
try
    if isfield(zef,'compartment_tags') && ~isempty(zef.compartment_tags)
        for k = 1:length(zef.compartment_tags)
            tag = zef.compartment_tags{k};
            % Get compartment name (use name if available, otherwise use tag)
            name_field = [tag '_name'];
            if isfield(zef, name_field) && ~isempty(zef.(name_field))
                comp_name = zef.(name_field);
                % Handle string/cell conversion
                if iscell(comp_name)
                    comp_name = comp_name{1};
                elseif isstring(comp_name)
                    comp_name = char(comp_name);
                end
                % Ensure it's a char array
                if ~ischar(comp_name)
                    comp_name = tag;
                end
            else
                comp_name = tag;
            end
            % Check if compartment is active
            on_field = [tag '_on'];
            if isfield(zef, on_field) && zef.(on_field)
                comp_name = [comp_name ' (active)'];
            else
                comp_name = [comp_name ' (inactive)'];
            end
            compartment_items{end+1} = comp_name;
            compartment_items_data{end+1} = tag;
        end
    else
        compartment_items = {'No compartments available'};
        compartment_items_data = {''};
    end
catch ME
    compartment_items = {'Error loading compartments'};
    compartment_items_data = {''};
end

% Set initial selection based on zef.dti_apply_to_compartments
initial_selection = {};
if isfield(zef,'dti_apply_to_compartments') && ~isempty(zef.dti_apply_to_compartments)
    if ischar(zef.dti_apply_to_compartments) || isstring(zef.dti_apply_to_compartments)
        initial_selection = {char(zef.dti_apply_to_compartments)};
    elseif iscell(zef.dti_apply_to_compartments)
        initial_selection = zef.dti_apply_to_compartments;
    end
    % Filter to only include tags that exist in compartment_items_data
    if ~isempty(initial_selection) && ~isempty(compartment_items_data)
        valid_indices = ismember(initial_selection, compartment_items_data);
        initial_selection = initial_selection(valid_indices);
    end
end

% If no initial selection, default to gray and white matter if available
if isempty(initial_selection) && ~isempty(compartment_items_data)
    default_tags = {'g', 'w'};
    for dt = default_tags
        idx = find(strcmp(compartment_items_data, dt{1}), 1);
        if ~isempty(idx)
            initial_selection{end+1} = dt{1};
        end
    end
end

% Create listbox for compartment selection (multi-select)
zef.h_dti_compartments = uilistbox(zef.h_dti_conductivity_tool, ...
    'Items', compartment_items, ...
    'ItemsData', compartment_items_data, ...
    'Multiselect', 'on', ...
    'Position', [PANEL_MARGIN+140 COMPART_Y-30 320 COMPART_HEIGHT], ...
    'Value', initial_selection, ...
    'ValueChangedFcn', 'zef_dti_conductivity_update_compartments;');

% Help text for compartment selection
