              '1. Select Reference MRI file (e.g. orig.mgz from recon-all output)', ...
              '2. Select FA file (fa.nii.gz from dt_recon output)', ...
              '3. Select register.dat (from dt_recon output directory)', ...
              '4. Click "Load" to import (matrices are auto-extracted)', ...
              '5. Select conversion model and adjust parameters', ...
              '6. Set interpolation mode and radius', ...
              '7. Select compartments to apply DTI conductivity', ...
              '8. Click "Apply to Mesh" to update conductivity', ...
