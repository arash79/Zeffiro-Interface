    'Text', '(Hold Ctrl/Cmd to select multiple)', ...
    'Position', [PANEL_MARGIN+10 COMPART_Y + 60 270 30], ...
    'FontSize', 9, ...
    'FontColor', [0.5 0.5 0.5]);

